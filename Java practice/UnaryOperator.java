package com.Operators;

public class UnaryOperator {
    public static void main(String[] args) {
        int i = 20;
        int j = 6;
        System.out.println(i);
        System.out.println(++i);
        System.out.println(i++);
        System.out.println(i);

        System.out.println();

        System.out.println(i);
        System.out.println(--i);
        System.out.println(i--);
        System.out.println(i);


    }
}
